#!/usr/bin/env python3
"""Exports which games show each tool form option, from the $x_game conditions around each input in src/tool_*.php.
Writes js/data/fieldGames.js: { 'tool_x.php': { field: [game slugs] } }. Only options hidden for some games are listed."""
import os, re, glob, json
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
SLUGS={'AD&D':'add','BD&D':'bdd','BFRPG':'bfrpg','Broken Urthe':'urthe','Gamma World':'gamma','Labyrinth Lord':'lablord','Metamorphosis Alpha':'meta','Millenniums & Mutations':'millen','Mutant Future':'mutfut','Necropalyx':'necro','OSRIC':'osric','Space Ryft':'ryft','Swords & Wizardry':'sandw','Tunnels & Trolls 5th Edition':'tt5e','Tunnels & Trolls 7th Edition':'tt7e','Fantasy':'fantasy','Survival Horror':'horror','Science-Fiction':'scifi','Post-Apocalyptic':'apoc','Wizardry & Warriors':'ww','Swords & Six-Siders':'ssxs','Tunnels & Trolls Deluxe':'ttde','Data':'data'}
GAMES=list(SLUGS)
def pre(c): return re.sub(r'\(?\$run_program\s*!=\s*1\)?|\(?\$menu_section\s*==\s*\d+\)?','True',c)
def gameonly(c): 
    c=pre(c)
    r=re.sub(r'\$x_game\s*(==|!=)\s*"([^"]*)"','X',c); return not re.search(r'\$',r)
def ev(c,g):
    c=pre(c)
    e=re.sub(r'\$x_game\s*(==|!=)\s*"([^"]*)"',lambda m:repr((g==m.group(2))==(m.group(1)=='==')),c)
    e=e.replace('||',' or ').replace('&&',' and ').replace('!',' not ')
    return eval(e)
out={}
for fn in sorted(glob.glob('src/tool_*.php')):
    s=open(fn,encoding='latin-1').read()
    end=s.find('SubmitButton'); 
    if end<0: continue
    s=s[:end]
    stack=[];names={}
    for m in re.finditer(r'<\?php(.*?)\?>|name=["\']([\w\[\]]+)["\']',s,re.S):
        if m.group(2):
            n=m.group(2); conds=[c for c in stack]
            names.setdefault(n,[]).append(conds); continue
        code=m.group(1)
        for t in re.finditer(r'\}\s*else\s*if\s*\((.*)\)\s*\{|\}\s*else\s*\{|\}|(?<![\w])if\s*\((.*)\)\s*\{',code):
            tx=t.group(0)
            if tx.startswith('}') and 'else if' in tx:
                prev=stack.pop() if stack else 'True'; stack.append('(not (%s)) and (%s)'%(prev,t.group(1)))
            elif tx.startswith('}') and 'else' in tx:
                prev=stack.pop() if stack else 'True'; stack.append('not (%s)'%prev)
            elif tx=='}':
                if stack: stack.pop()
            else: stack.append('(%s)'%t.group(2))
    res={}
    for n,occ in names.items():
        games=set();ok=True
        for conds in occ:
            c=' and '.join(conds) or 'True'
            if not gameonly(c): ok=False;break
            try: games|={g for g in GAMES if ev(c,g)}
            except Exception: ok=False;break
        if ok and games!=set(GAMES): res[n]=sorted(games)
    if res: out[fn.split('/')[-1]]={k:[SLUGS[g] for g in GAMES if g in v] for k,v in sorted(res.items())}
for k in [k for k,v in out.items() if not v]: del out[k]
with open('js/data/fieldGames.js','w') as f:
    f.write('// Generated by js/export-field-games.py from the $x_game conditions in src/tool_*.php forms.\nwindow.WZ_DATA = window.WZ_DATA || {};\nwindow.WZ_DATA.fieldGames = '+json.dumps(out,separators=(',',':'))+';\n')
print(len(out),'tools',sum(len(v) for v in out.values()),'options')
